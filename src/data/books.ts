import type { EraId } from '../types';

/**
 * Books. The library is not a stat nudge: you pick something off a
 * shelf that changes every time you look at it, and you read it a
 * page at a time. Longer books teach more but take longer to finish.
 *
 * Old books survive into later eras — a Roman can not read a novel,
 * but you can still read the Iliad. Gate with `fromEra` for the
 * earliest period that has it, and with `year` for the calendar year
 * it appears from. Omit both and it was always there.
 *
 * To extend: add a row. Gate it with `fromEra` and `minAge` / `maxAge`
 * so the right readers find it.
 */

export interface BookDef {
  id: string;
  /** e.g. "Meditations" */
  title: string;
  /** e.g. "Philosophy" — shown in the list */
  genre: string;
  /** real page count; sittings are derived from it */
  pages: number;
  /** smarts gained on finishing, before fatigue */
  smarts: number;
  happiness?: number;
  minAge?: number;
  maxAge?: number;
  /** earliest period that has it; later periods keep it */
  fromEra?: EraId;
  /** calendar year it appears from; omit for ageless books */
  year?: number;
  /** popup line when finished */
  notice: string;
  /** journal line when finished */
  journal: string;
}

